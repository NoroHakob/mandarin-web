export type IoniconName = keyof typeof IONICONS;

const FALLBACK_ICON: IconType = IoSchoolOutline;

type IoniconProps = {
  name: string;
  size?: number;
  color?: string;
  className?: string;
};

/** Renders an Ionicons glyph by its Expo name, falling back to a generic icon for unknown names. */
export default function Ionicon({ name, size = 24, color, className }: IoniconProps) {
  const Icon = (IONICONS as Record<string, IconType>)[name] ?? FALLBACK_ICON;
  return <Icon size={size} color={color} className={className} aria-hidden />;
}
